def format_hit(hit: dict[str, str]) -> str:
    title = hit.get("title") or "Конструкция"
    body = hit.get("body") or ""
    text = f"<b>{title}</b>\n\n{body}\n\n<i>Не рекомендация сделки.</i>"
    n = len(text.replace("<b>", "").replace("</b>", "").replace("<i>", "").replace("</i>", ""))
    if n < 900:
        text += "\nГраница применимости: без чужого депозита и без сигналов на вход."
    return text


