def select_ai_ops(brief: str) -> dict[str, Any]:
    t = (brief or "").lower()
    if "дубл" in t or "повтор" in t:
        return AI_OPS["dup_detect"]
    if "отказ" in t:
        return AI_OPS["refuse_class"]
    if "черновик" in t or "ответ" in t:
        return AI_OPS["draft_reply"]
    if "переписк" in t or "саммари" in t or "crm" in t:
        return AI_OPS["thread_to_crm"]
    return AI_OPS["qualify_lead"]
