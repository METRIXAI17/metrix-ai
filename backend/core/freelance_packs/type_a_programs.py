def select_type_a_pack(brief: str, flags: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    t = (brief or "").lower()
    flags = flags or []
    codes = {f.get("id") for f in flags}
    if "P6" in codes:
        return PACKS["A2"]
    if "P9" in codes or "отчёт" in t or "понедельник" in t:
        return PACKS["A4"]
    if "сдач" in t or "handover" in t or "доступ" in t:
        return PACKS["A6"]
    if "статус" in t:
        return PACKS["A3"]
    if "amo" in t or "bitrix" in t or "битрикс" in t or "таблиц" in t:
        return PACKS["A5"]
    if "хозяин" in t or "sla" in t or "минут" in t:
        return PACKS["A2"]
    return PACKS["A1"]


def render_pack_prompt(pack: dict[str, Any], brief: str) -> str:
    return str(pack.get("prompt") or "").format(brief=(brief or "")[:800])
