def list_teammates() -> list[dict[str, Any]]:
    out = []
    for k in LIVE_IDS:
        t = TEAMMATES[k]
        out.append(
            {
                "id": t["id"],
                "codename": t["codename"],
                "title": t["title"],
                "size": t["size"],
                "accent": t["accent"],
                "image": t.get("image") or "",
                "job": t["job"],
                "pain": t["pain"],
                "user_facing": t["user_facing"],
            }
        )
    return out


