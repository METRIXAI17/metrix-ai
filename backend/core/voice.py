def clip(text: str, n: int = 280) -> str:
    t = " ".join((text or "").split())
    if len(t) <= n:
        return t
    return t[: n - 1].rstrip() + "…"


def first_sentence(text: str, fallback: str = "") -> str:
    t = " ".join((text or "").split())
    if not t:
        return fallback
    for sep in (". ", "! ", "? ", "\n"):
        i = t.find(sep)
        if 0 < i < 180:
            return t[: i + 1].strip()
    return clip(t, 160)


